(** * Trace.v -- the comparison method and the reuse theorems of Part I.

    Mechanises the comparison method of Section 4 for an encoding in which
    events name regions by index, the dereference analysis shared by Theorems
    A2, B1, B1r, Corollary A3, and Theorem B2, and Lemma 4's composition, over
    an abstract machine, from
    [docs/proofs/COMPOSITE_REGION_REUSE_PROOF.md].

    The machine.  A run is generated by [next], a function from the
    observation history to the next event, so the machine is deterministic
    given its environment, the environment's symbolic behavior is folded into
    [next], and no event depends on an address, which is M8.  An event names a
    region by its allocation index, its provenance, never by its address.

    The memory.  A cell is a bump interval, one per region, or a plan slot.
    An allocation writes its whole construction into its cell, so the bytes a
    cell presents are those of the last region allocated into it.  This
    region-granular model observes every divergence the theorems must exclude,
    since a dereference of a region whose cell was taken returns the later
    region's bytes.  Allocation reads no region, so the inline copy of
    composite operands in M3(vi) is not expressed.
    Construction bytes are fixed at allocation, which is M1.  A handle carries
    its region's creation epoch, a view carries its source's, a dereference
    succeeds exactly when that epoch is current, and epochs advance only at
    [EAdvance], never repeating, which is M2 with M4.  Copies of the
    escape-copy discipline live in a separate copy store, written once at
    their creation from a dereference of their source, which is Definition 9's
    faithfulness, stability, epoch stamping, recursion, and depth. *)

From Stdlib Require Import List Arith Lia.
Import ListNotations.

Section Trace.

Variables Site Bytes View Scalar : Type.
(** [sel v b] is the sub-interval of [b] a view [v] addresses. *)
Variable sel : View -> Bytes -> Bytes.

Inductive src : Type := SReg (r : nat) | SCopy (c : nat).

Inductive event : Type :=
| EStep
| EAlloc (s : Site) (b : Bytes)
| EDeref (x : src) (v : View)
| ECopy (x : src) (v : View)
| EAdvance
| EOut (o : Scalar).

Inductive obs : Type := ONone | OStale | OBytes (b : Bytes) | OScalar (o : Scalar).

Inductive cell : Type := Bump (r : nat) | Slot (k : nat).

Definition cell_eq_dec : forall a b : cell, {a = b} + {a <> b}.
Proof. decide equality; apply Nat.eq_dec. Defined.

(** A plan assigns a reused site its slot.  Sites sharing a slot form an arm
    group, distinct slots are distinct elements, and cells are disjoint by
    construction, which is well-formedness. *)
Definition plan := Site -> option nat.
Definition baseline : plan := fun _ => None.

Definition cell_of (P : plan) (s : Site) (r : nat) : cell :=
  match P s with Some k => Slot k | None => Bump r end.

Record region := mkregion { r_site : Site; r_epoch : nat; r_bytes : Bytes }.

Record state := mkstate {
  st_epoch : nat;
  st_regs : list region;
  st_owner : cell -> option nat;
  st_copies : list (nat * Bytes)
}.

Definition init : state := mkstate 0 [] (fun _ => None) [].

Definition read (P : plan) (st : state) (x : src) (v : View) : obs :=
  match x with
  | SReg r =>
      match nth_error (st_regs st) r with
      | Some g =>
          if Nat.eqb (r_epoch g) (st_epoch st) then
            match st_owner st (cell_of P (r_site g) r) with
            | Some r' =>
                match nth_error (st_regs st) r' with
                | Some g' => OBytes (sel v (r_bytes g'))
                | None => OStale
                end
            | None => OStale
            end
          else OStale
      | None => OStale
      end
  | SCopy c =>
      match nth_error (st_copies st) c with
      | Some (e, b) => if Nat.eqb e (st_epoch st) then OBytes (sel v b) else OStale
      | None => OStale
      end
  end.

Definition exec (P : plan) (ev : event) (st : state) : obs * state :=
  match ev with
  | EStep => (ONone, st)
  | EAlloc s b =>
      let r := length (st_regs st) in
      (ONone, mkstate (st_epoch st)
                      (st_regs st ++ [mkregion s (st_epoch st) b])
                      (fun c => if cell_eq_dec c (cell_of P s r) then Some r else st_owner st c)
                      (st_copies st))
  | EDeref x v => (read P st x v, st)
  | ECopy x v =>
      match read P st x v with
      | OBytes b => (OBytes b, mkstate (st_epoch st) (st_regs st) (st_owner st)
                                       (st_copies st ++ [(st_epoch st, b)]))
      | o => (o, st)
      end
  | EAdvance => (ONone, mkstate (S (st_epoch st)) (st_regs st) (st_owner st) (st_copies st))
  | EOut o => (OScalar o, st)
  end.

Fixpoint run (P : plan) (st : state) (evs : list event) : list obs * state :=
  match evs with
  | [] => ([], st)
  | e :: es =>
      let '(o, st1) := exec P e st in
      let '(os, st2) := run P st1 es in
      (o :: os, st2)
  end.

Definition obs_of (P : plan) (evs : list event) : list obs := fst (run P init evs).
Definition after (P : plan) (evs : list event) : state := snd (run P init evs).

(** ** Runs generated by the machine. *)
Variable next : list obs -> option event.

Fixpoint gen (P : plan) (n : nat) : list event :=
  match n with
  | 0 => []
  | S n' =>
      let e := gen P n' in
      match next (obs_of P e) with
      | Some ev => e ++ [ev]
      | None => e
      end
  end.

(** Definition 5's soundness.  Every prefix of every run agrees, for the
    machine and environment behavior [next], which the closed theorems
    quantify over. *)
Definition sound (P : plan) : Prop :=
  forall n, obs_of P (gen P n) = obs_of baseline (gen baseline n).

(** ** Bookkeeping over event lists. *)
Fixpoint nallocs (l : list event) : nat :=
  match l with
  | [] => 0
  | EAlloc _ _ :: l' => S (nallocs l')
  | _ :: l' => nallocs l'
  end.

Fixpoint nadv (l : list event) : nat :=
  match l with
  | [] => 0
  | EAdvance :: l' => S (nadv l')
  | _ :: l' => nadv l'
  end.

Lemma nallocs_app : forall a b, nallocs (a ++ b) = nallocs a + nallocs b.
Proof. induction a as [|e a IH]; intros b; [reflexivity|]. destruct e; simpl; rewrite ?IH; reflexivity. Qed.

Lemma nadv_app : forall a b, nadv (a ++ b) = nadv a + nadv b.
Proof. induction a as [|e a IH]; intros b; [reflexivity|]. destruct e; simpl; rewrite ?IH; reflexivity. Qed.

(** A read of region [r] is a dereference or a copy whose source is [r]. *)
Definition is_reg_read (e : event) (r : nat) : Prop :=
  match e with
  | EDeref (SReg r') _ => r' = r
  | ECopy (SReg r') _ => r' = r
  | _ => False
  end.

Lemma run_app : forall P st a b,
  run P st (a ++ b) =
  (fst (run P st a) ++ fst (run P (snd (run P st a)) b), snd (run P (snd (run P st a)) b)).
Proof.
  intros P st a. revert st. induction a as [|e a IH]; intros st b; simpl.
  - destruct (run P st b); reflexivity.
  - destruct (exec P e st) as [o st1]. rewrite IH.
    destruct (run P st1 a) as [os1 st2]. simpl. destruct (run P st2 b). reflexivity.
Qed.

Lemma after_app : forall P a b, after P (a ++ b) = snd (run P (after P a) b).
Proof. intros. unfold after. rewrite run_app. reflexivity. Qed.

(** The region table and epoch evolve identically under every plan. *)
Lemma run_cons_snd : forall P st e l,
  snd (run P st (e :: l)) = snd (run P (snd (exec P e st)) l).
Proof.
  intros. simpl. destruct (exec P e st) as [o st1]. simpl.
  destruct (run P st1 l). reflexivity.
Qed.

Lemma exec_regs_epoch : forall P e st,
  exists tail, st_regs (snd (exec P e st)) = st_regs st ++ tail /\
               length tail = nallocs [e] /\
               st_epoch (snd (exec P e st)) = st_epoch st + nadv [e].
Proof.
  intros P e st. destruct e as [| s b | x v | x v | | o]; simpl;
    try (exists []; rewrite app_nil_r; repeat split; lia).
  - exists [mkregion s (st_epoch st) b]. repeat split; simpl; lia.
  - destruct (read P st x v); simpl; exists []; rewrite app_nil_r; repeat split; lia.
Qed.

Lemma run_regs_epoch : forall P st l,
  exists tail, st_regs (snd (run P st l)) = st_regs st ++ tail /\
               length tail = nallocs l /\
               st_epoch (snd (run P st l)) = st_epoch st + nadv l.
Proof.
  intros P st l. revert st. induction l as [|e l IH]; intros st.
  - exists []. simpl. rewrite app_nil_r. repeat split; lia.
  - rewrite run_cons_snd.
    destruct (exec_regs_epoch P e st) as [t1 [A1 [A2 A3]]].
    destruct (IH (snd (exec P e st))) as [t2 [B1 [B2 B3]]].
    exists (t1 ++ t2). rewrite B1, A1, app_assoc. split; [reflexivity|].
    change (e :: l) with ([e] ++ l). rewrite nallocs_app, nadv_app, length_app. lia.
Qed.

Lemma after_len : forall P l, length (st_regs (after P l)) = nallocs l.
Proof.
  intros P l. destruct (run_regs_epoch P init l) as [t [H1 [H2 _]]].
  unfold after. rewrite H1. simpl. assumption.
Qed.

Lemma after_epoch : forall P l, st_epoch (after P l) = nadv l.
Proof.
  intros P l. destruct (run_regs_epoch P init l) as [t [_ [_ H3]]].
  unfold after. rewrite H3. reflexivity.
Qed.

Lemma after_region : forall P p1 s b m,
  nth_error (st_regs (after P (p1 ++ EAlloc s b :: m))) (nallocs p1)
  = Some (mkregion s (nadv p1) b).
Proof.
  intros P p1 s b m. rewrite after_app, run_cons_snd.
  destruct (run_regs_epoch P (snd (exec P (EAlloc s b) (after P p1))) m) as [t [H1 _]].
  rewrite H1. simpl. rewrite <- app_assoc, nth_error_app2; rewrite after_len; [|lia].
  rewrite Nat.sub_diag, after_epoch. reflexivity.
Qed.

(** Every region index below the count has an allocation. *)
Lemma split_alloc : forall p r, r < nallocs p ->
  exists p1 s b m, p = p1 ++ EAlloc s b :: m /\ nallocs p1 = r.
Proof.
  induction p as [|e p IH]; intros r Hr; simpl in Hr; [lia|].
  destruct e as [| s b | x v | x v | | o];
    try (destruct (IH r Hr) as [p1 [s1 [b1 [m [-> Hn]]]]];
         eexists (_ :: p1), s1, b1, m; split; [reflexivity|simpl; assumption]).
  destruct r as [|r].
  - exists [], s, b, p. split; reflexivity.
  - destruct (IH r) as [p1 [s' [b' [m [-> Hn]]]]]; [lia|].
    exists (EAlloc s b :: p1), s', b', m. split; [reflexivity|simpl; lia].
Qed.

(** ** The comparison method, mechanised.

    [corr] is the correspondence of the two regimes' states, identical except
    in their memories, the baseline presenting each region in its own bump
    interval.  [live P sp sb r] says the plan's cell for [r] still presents
    [r] whenever a dereference of [r] would succeed. *)
Definition corr (sp sb : state) : Prop :=
  st_epoch sp = st_epoch sb /\ st_regs sp = st_regs sb /\ st_copies sp = st_copies sb /\
  (forall r, r < length (st_regs sb) -> st_owner sb (Bump r) = Some r).

Definition live (P : plan) (sp sb : state) (r : nat) : Prop :=
  forall g, nth_error (st_regs sb) r = Some g -> r_epoch g = st_epoch sb ->
            st_owner sp (cell_of P (r_site g) r) = Some r.

Definition guard (P : plan) (sp sb : state) (e : event) : Prop :=
  match e with
  | EDeref (SReg r) _ => live P sp sb r
  | ECopy (SReg r) _ => live P sp sb r
  | _ => True
  end.

Lemma read_corr : forall P sp sb x v,
  corr sp sb ->
  (match x with SReg r => live P sp sb r | SCopy _ => True end) ->
  read P sp x v = read baseline sb x v.
Proof.
  intros P sp sb x v [He [Hr [Hc Hb]]] Hl. destruct x as [r|c]; simpl.
  - rewrite Hr, He. destruct (nth_error (st_regs sb) r) as [g|] eqn:Hg; [|reflexivity].
    destruct (Nat.eqb (r_epoch g) (st_epoch sb)) eqn:Hep; [|reflexivity].
    apply Nat.eqb_eq in Hep. rewrite (Hl g Hg Hep). unfold cell_of, baseline.
    rewrite Hb; [reflexivity|].
    apply nth_error_Some. rewrite Hg. discriminate.
  - rewrite Hc, He. reflexivity.
Qed.

Lemma exec_corr : forall P sp sb e,
  corr sp sb -> guard P sp sb e ->
  fst (exec P e sp) = fst (exec baseline e sb) /\
  corr (snd (exec P e sp)) (snd (exec baseline e sb)).
Proof.
  intros P sp sb e Hc Hg. pose proof Hc as [He [Hr [Hcp Hb]]].
  destruct e as [| s b | x v | x v | | o]; simpl.
  - split; [reflexivity|assumption].
  - split; [reflexivity|]. unfold corr; simpl. rewrite He, Hr, Hcp.
    repeat split; try reflexivity.
    intros r Hlt. rewrite length_app in Hlt. simpl in Hlt.
    destruct (Nat.eq_dec r (length (st_regs sb))) as [->|Hne]; simpl; [reflexivity|].
    apply Hb. lia.
  - split; [|assumption]. apply read_corr; [assumption|]. destruct x; [exact Hg|exact I].
  - assert (Hrd : read P sp x v = read baseline sb x v)
      by (apply read_corr; [assumption|]; destruct x; [exact Hg|exact I]).
    rewrite Hrd. destruct (read baseline sb x v); simpl; try (split; [reflexivity|assumption]).
    split; [reflexivity|]. unfold corr; simpl. rewrite He, Hr, Hcp. repeat split; try reflexivity.
    exact Hb.
  - split; [reflexivity|]. unfold corr; simpl. rewrite He, Hr, Hcp. repeat split; try reflexivity.
    exact Hb.
  - split; [reflexivity|assumption].
Qed.

Fixpoint ok (P : plan) (sp sb : state) (evs : list event) : Prop :=
  match evs with
  | [] => True
  | e :: es => guard P sp sb e /\ ok P (snd (exec P e sp)) (snd (exec baseline e sb)) es
  end.

Lemma memory_agrees : forall P evs sp sb,
  corr sp sb -> ok P sp sb evs -> fst (run P sp evs) = fst (run baseline sb evs).
Proof.
  intros P evs. induction evs as [|e evs IH]; intros sp sb Hc Hok; simpl; [reflexivity|].
  destruct Hok as [Hg Hok]. destruct (exec_corr P sp sb e Hc Hg) as [Ho Hc'].
  destruct (exec P e sp) as [op sp1] eqn:Ep. destruct (exec baseline e sb) as [ob sb1] eqn:Eb.
  simpl in *. specialize (IH sp1 sb1 Hc' Hok).
  destruct (run P sp1 evs) as [osp ?]. destruct (run baseline sb1 evs) as [osb ?].
  simpl in *. subst. reflexivity.
Qed.

Lemma ok_intro : forall P evs sp sb,
  (forall p e q, evs = p ++ e :: q ->
     guard P (snd (run P sp p)) (snd (run baseline sb p)) e) ->
  ok P sp sb evs.
Proof.
  intros P evs. induction evs as [|e evs IH]; intros sp sb H; simpl; [exact I|].
  split.
  - apply (H [] e evs). reflexivity.
  - apply IH. intros p e' q Heq.
    specialize (H (e :: p) e' q). rewrite Heq in H. specialize (H eq_refl).
    rewrite !run_cons_snd in H. exact H.
Qed.

(** [nowrite P c n m] says no allocation in [m] targets cell [c], the first
    allocation of [m] receiving region index [n]. *)
Fixpoint nowrite (P : plan) (c : cell) (n : nat) (m : list event) : Prop :=
  match m with
  | [] => True
  | EAlloc s _ :: m' => cell_of P s n <> c /\ nowrite P c (S n) m'
  | _ :: m' => nowrite P c n m'
  end.

Lemma nowrite_keeps : forall P c m st o,
  nowrite P c (length (st_regs st)) m -> st_owner st c = o ->
  st_owner (snd (run P st m)) c = o.
Proof.
  intros P c m. induction m as [|e m IH]; intros st o Hn Ho; [exact Ho|].
  rewrite run_cons_snd.
  destruct e as [| s b | x v | x v | | o']; simpl in Hn.
  - simpl. apply IH; assumption.
  - destruct Hn as [Hne Hn]. apply IH.
    + simpl. rewrite length_app. simpl. rewrite Nat.add_1_r. exact Hn.
    + simpl. destruct (cell_eq_dec c (cell_of P s (length (st_regs st)))) as [E|_];
        [exfalso; apply Hne; symmetry; exact E|exact Ho].
  - simpl. apply IH; assumption.
  - simpl. destruct (read P st x v); simpl; apply IH; assumption.
  - simpl. apply IH; assumption.
  - simpl. apply IH; assumption.
Qed.

Lemma owner_after_alloc : forall P p1 s b m,
  nowrite P (cell_of P s (nallocs p1)) (S (nallocs p1)) m ->
  st_owner (after P (p1 ++ EAlloc s b :: m)) (cell_of P s (nallocs p1)) = Some (nallocs p1).
Proof.
  intros P p1 s b m Hn. rewrite after_app.
  change (EAlloc s b :: m) with ([EAlloc s b] ++ m). rewrite run_app. simpl.
  apply nowrite_keeps.
  - simpl. rewrite length_app, after_len. simpl. rewrite Nat.add_1_r. assumption.
  - simpl. rewrite after_len.
    destruct (cell_eq_dec (cell_of P s (nallocs p1)) (cell_of P s (nallocs p1))) as [_|E];
      [reflexivity|contradiction].
Qed.

(** A bump cell is never written again, since region indices only grow. *)
Lemma nowrite_bump : forall P r m n, r < n -> nowrite P (Bump r) n m.
Proof.
  intros P r m. induction m as [|e m IH]; intros n Hlt; simpl; [exact I|].
  destruct e; try (apply IH; assumption).
  split; [|apply IH; lia].
  unfold cell_of. destruct (P s); [discriminate|]. intros E. injection E. lia.
Qed.

(** ** Lemma 4, composition.

    [slot_safe P k evs] is the per-element dereference obligation.  At every
    read of a region allocated into slot [k] in the same epoch, no allocation
    since has targeted the slot.  The plan is sound when every slot is safe on
    every baseline run.  The comparison method makes the ordered induction of
    the prose proof unnecessary here, because one simulation relates the
    whole plan to the baseline at once. *)
Definition slot_safe (P : plan) (k : nat) (evs : list event) : Prop :=
  forall p1 s b m e q,
    evs = p1 ++ EAlloc s b :: m ++ e :: q ->
    P s = Some k -> is_reg_read e (nallocs p1) -> nadv m = 0 ->
    nowrite P (Slot k) (S (nallocs p1)) m.

Lemma guards_hold : forall P evs,
  (forall k, slot_safe P k evs) ->
  forall p e q, evs = p ++ e :: q -> guard P (after P p) (after baseline p) e.
Proof.
  intros P evs Hs p e q Heq.
  assert (Hlive : forall r, is_reg_read e r -> live P (after P p) (after baseline p) r).
  { intros r Hr g Hg Hep.
    assert (Hlt : r < nallocs p).
    { rewrite <- (after_len baseline p). apply nth_error_Some. rewrite Hg. discriminate. }
    destruct (split_alloc p r Hlt) as [p1 [s [b [m [-> Hn]]]]].
    subst r. rewrite after_region in Hg. injection Hg as <-. simpl in Hep |- *.
    rewrite after_epoch, nadv_app in Hep. simpl in Hep.
    assert (Hm0 : nadv m = 0) by lia.
    unfold cell_of. destruct (P s) as [k|] eqn:Hk.
    - pose proof (owner_after_alloc P p1 s b m) as Ho. unfold cell_of in Ho. rewrite Hk in Ho.
      apply Ho. apply (Hs k p1 s b m e q); [|assumption|assumption|assumption].
      rewrite Heq, <- app_assoc. reflexivity.
    - pose proof (owner_after_alloc P p1 s b m) as Ho. unfold cell_of in Ho. rewrite Hk in Ho.
      apply Ho. apply nowrite_bump. lia. }
  destruct e as [| | [r|c] v | [r|c] v | |]; simpl; try exact I; apply Hlive; reflexivity.
Qed.

Lemma obs_agree : forall P evs,
  (forall k, slot_safe P k evs) -> obs_of P evs = obs_of baseline evs.
Proof.
  intros P evs Hk. unfold obs_of. apply memory_agrees.
  - unfold corr; simpl. repeat split; intros r Hr; simpl in Hr; lia.
  - apply ok_intro. intros p e q Heq. apply (guards_hold P evs Hk p e q Heq).
Qed.

(** The plan run executes the baseline's event sequence, which Theorem C's
    proof uses to identify the plan's bump allocations with the baseline
    traversal's non-reused executions. *)
Theorem plan_follows_baseline : forall P,
  (forall n k, slot_safe P k (gen baseline n)) -> forall n, gen P n = gen baseline n.
Proof.
  intros P Hs. induction n as [|n IH]; [reflexivity|]. simpl.
  rewrite IH, (obs_agree _ _ (Hs n)). reflexivity.
Qed.

Theorem lemma4_composition : forall P,
  (forall n k, slot_safe P k (gen baseline n)) -> sound P.
Proof.
  intros P Hs n. rewrite (plan_follows_baseline P Hs). apply obs_agree. apply Hs.
Qed.

(** ** The slot theorem.

    Every two consecutive allocations into one slot are separated by an epoch
    boundary, or by the end of the first allocation's scope, [send] giving the
    scope end of the execution at each position, with no read of the first
    region at or after that end.  The clearance lemmas of [Clearance.v]
    discharge the second disjunct's read condition. *)
Definition clear_after (evs : list event) (send : nat -> nat) (j r : nat) : Prop :=
  forall p e q, evs = p ++ e :: q -> is_reg_read e r -> send j <= length p -> False.

Definition separated (P : plan) (k : nat) (send : nat -> nat) (evs : list event) : Prop :=
  forall p1 s1 b1 m s2 b2 q,
    evs = p1 ++ EAlloc s1 b1 :: m ++ EAlloc s2 b2 :: q ->
    P s1 = Some k -> P s2 = Some k -> nowrite P (Slot k) (S (nallocs p1)) m ->
    0 < nadv m \/
    (send (length p1) <= S (length p1 + length m) /\
     clear_after evs send (length p1) (nallocs p1)).

(** Either [m] never writes [c], or it has a first write. *)
Lemma first_write : forall P c m n,
  nowrite P c n m \/
  exists m1 s b m2, m = m1 ++ EAlloc s b :: m2 /\ nowrite P c n m1 /\
                    cell_of P s (n + nallocs m1) = c.
Proof.
  intros P c m. induction m as [|e m IH]; intros n; [left; exact I|].
  assert (Hpass : forall e0, (forall n0, nowrite P c n0 (e0 :: m) = nowrite P c n0 m) ->
                  nallocs [e0] = 0 ->
                  nowrite P c n (e0 :: m) \/
                  exists m1 s b m2, e0 :: m = m1 ++ EAlloc s b :: m2 /\ nowrite P c n m1 /\
                                    cell_of P s (n + nallocs m1) = c).
  { intros e0 Hnw Hna. rewrite Hnw.
    destruct (IH n) as [H|[m1 [s1 [b1 [m2 [-> [H1 H2]]]]]]]; [left; exact H|right].
    exists (e0 :: m1), s1, b1, m2. split; [reflexivity|].
    destruct e0; simpl in Hna |- *; try discriminate; split; assumption. }
  destruct e as [| s b | x v | x v | | o];
    try (apply Hpass; [reflexivity|reflexivity]).
  simpl. destruct (cell_eq_dec (cell_of P s n) c) as [E|Ne].
  - right. exists [], s, b, m. simpl. rewrite Nat.add_0_r. auto.
  - destruct (IH (S n)) as [H|[m1 [s' [b' [m2 [-> [H1 H2]]]]]]].
    + left. auto.
    + right. exists (EAlloc s b :: m1), s', b', m2. simpl. rewrite <- Nat.add_succ_comm. auto.
Qed.

Theorem slot_theorem : forall P k send evs,
  separated P k send evs -> slot_safe P k evs.
Proof.
  intros P k send evs Hsep p1 s b m e q Heq Hk Hrd Hm0.
  destruct (first_write P (Slot k) m (S (nallocs p1))) as [H|[m1 [s' [b' [m2 [-> [H1 H2]]]]]]];
    [assumption|exfalso].
  assert (Hk' : P s' = Some k) by (unfold cell_of in H2; destruct (P s'); [congruence|discriminate]).
  destruct (Hsep p1 s b m1 s' b' (m2 ++ e :: q)) as [Hadv|[Hle Hclr]];
    [rewrite Heq; repeat (rewrite <- app_assoc; simpl); reflexivity|assumption|assumption|assumption| |].
  - rewrite nadv_app in Hm0. simpl in Hm0. lia.
  - apply (Hclr (p1 ++ EAlloc s b :: m1 ++ EAlloc s' b' :: m2) e q).
    + rewrite Heq. repeat (rewrite <- app_assoc; simpl). reflexivity.
    + assumption.
    + rewrite length_app. simpl. rewrite length_app. simpl. lia.
Qed.

(** ** Theorem A2 at the trace level.

    At most one allocation into the shared slot occurs per epoch.  The prose
    derives this from the conditional instantiating at most once per cycle,
    from lexical containment, which [Bound.cond_one_arm] mechanises, and from
    each site executing at most once per cycle.  That counting step is a
    premise here. *)
Definition once_per_epoch (P : plan) (k : nat) (evs : list event) : Prop :=
  forall p1 s1 b1 m s2 b2 q,
    evs = p1 ++ EAlloc s1 b1 :: m ++ EAlloc s2 b2 :: q ->
    P s1 = Some k -> P s2 = Some k -> 0 < nadv m.

Theorem A2_arm_overlap : forall P k evs,
  once_per_epoch P k evs -> slot_safe P k evs.
Proof.
  intros P k evs Ho. apply (slot_theorem P k (fun _ => 0)).
  intros p1 s1 b1 m s2 b2 q Heq H1 H2 _. left. apply (Ho p1 s1 b1 m s2 b2 q); assumption.
Qed.

End Trace.
