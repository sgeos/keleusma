#!/usr/bin/env python3
"""Run a gate command, keep its full output in a log, and print a bounded summary.

An agent that reads a whole gate transcript carries it in context for the rest of
the session. This wrapper writes the transcript to a log file and prints only the
lines a reader needs to act, under rules chosen so that no failure is hidden.

1. The command, exit status, duration and log path are always printed, and the
   wrapper exits with the command's own status.
2. Every line matching a failure marker is printed, with a few lines of context
   after a panic or a compiler error, under the most recent step or test-binary
   header.
3. Summary lines, such as `test result:` and the nextest `Summary`, are printed.
4. A non-zero exit with no recognised failure marker prints the log's last lines,
   because an unrecognised failure is still a failure.
5. A zero exit with failure markers says so, because a passing status that
   contradicts its own output deserves a look.
6. When the marker lines exceed the limit, the elided count is printed and the
   log's last lines follow, so truncation is always visible.

The markers are tested against real cargo, nextest, clippy and rustfmt output in
`scripts/gate_summary_fixtures/`, regenerated by `capture.sh` there. A tool whose
output format changes can stop matching. Rule 4 is the guard for that case.

Usage: scripts/gate_summary.py [--log PATH] [--tail N] [--limit N] -- COMMAND...
"""

import argparse
import datetime
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

ANSI = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]|\x1b\([A-Za-z]|\x1b\][^\x07]*\x07")
# Leading whitespace is allowed because nextest indents each test's captured output.
FAILURE = re.compile(
    r"^\s*test .+ \.\.\. FAILED$"
    r"|^\s*(TRY \d+ )?(FAIL|TIMEOUT|ABORT|LEAK-FAIL|SIG[A-Z]+)\s+\["
    r"|panicked at"
    r"|^\s*error(\[E\d+\])?:"
    r"|^Diff in "
    r"|process didn't exit successfully"
    r"|has overflowed its stack|fatal runtime error"
    r"|^(Killed|Segmentation fault|Abort trap|Bus error)\b"
    r"|^\s*test result: FAILED"
)
SUMMARY = re.compile(r"^\s*test result: |^\s*Summary \[|^\s*Starting \d+ tests? across")
HEADER = re.compile(r"^=== .+ ===$|^\s*Running |^\s*Doc-tests ")
# Lines of context kept after a marker, for the message and location that follow it.
CONTEXT = ((re.compile(r"panicked at"), 4), (re.compile(r"^\s*error(\[E\d+\])?:"), 2))
DEFAULT_TAIL = 60
DEFAULT_LIMIT = 150


def clean(line):
    return ANSI.sub("", line).rstrip("\r\n")


def summarize(lines, status, tail=DEFAULT_TAIL, limit=DEFAULT_LIMIT):
    """Return the summary lines for a finished run. Pure, so fixtures can replay it."""
    text = [clean(line) for line in lines]
    shown = []
    markers = 0
    elided = 0
    header = None
    header_shown = None
    keep_until = -1
    for index, line in enumerate(text):
        if HEADER.search(line):
            header = line.strip()
            continue
        is_failure = bool(FAILURE.search(line))
        is_summary = bool(SUMMARY.search(line))
        in_context = index <= keep_until
        if not (is_failure or is_summary or in_context):
            continue
        if is_failure:
            markers += 1
            for pattern, extra in CONTEXT:
                if pattern.search(line):
                    keep_until = max(keep_until, index + extra)
        if len(shown) >= limit:
            elided += 1
            continue
        if (is_failure or in_context) and header is not None and header_shown != header:
            shown.append("[" + header + "]")
            header_shown = header
        shown.append(line)
    out = []
    if status != 0 and markers == 0:
        out.append("No failure marker was recognised in a failing run. Last lines of the log follow.")
    elif status == 0 and markers:
        out.append("The command exited 0, but " + str(markers) + " failure marker lines appear in its output.")
    out.extend(shown)
    if elided:
        out.append("... " + str(elided) + " further marker or summary lines are in the log.")
    if (status != 0 and markers == 0) or elided:
        out.append("--- last " + str(min(tail, len(text))) + " lines ---")
        out.extend(text[-tail:] if tail else [])
    return out


def run(command, log_path):
    """Run the command with merged output into the log. Return (status, seconds)."""
    started = time.monotonic()
    with open(log_path, "w", encoding="utf-8", errors="replace") as log:
        try:
            process = subprocess.Popen(command, stdout=log, stderr=subprocess.STDOUT)
        except OSError as error:
            log.write("gate_summary: could not start the command: " + str(error) + "\n")
            return 127, time.monotonic() - started
        status = process.wait()
    return status, time.monotonic() - started


def default_log():
    folder = Path(tempfile.gettempdir()) / "gate-summary"
    folder.mkdir(mode=0o700, exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%dT%H%M%S")
    return folder / (stamp + "-" + str(os.getpid()) + ".log")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--log", type=Path, help="where to keep the full output")
    parser.add_argument("--tail", type=int, default=DEFAULT_TAIL, help="log lines shown when needed")
    parser.add_argument("--limit", type=int, default=DEFAULT_LIMIT, help="marker and summary lines shown")
    parser.add_argument("command", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    command = args.command[1:] if args.command[:1] == ["--"] else args.command
    if not command:
        parser.error("give the command after --")
    if args.tail < 0 or args.limit < 1:
        parser.error("--tail must be at least 0 and --limit at least 1")
    log_path = args.log or default_log()
    status, seconds = run(command, log_path)
    # A negative status is a signal. Report it the way a shell does.
    exit_status = 128 - status if status < 0 else status
    with open(log_path, encoding="utf-8", errors="replace") as log:
        lines = log.readlines()
    verdict = "passed" if exit_status == 0 else "FAILED"
    signal_note = ", killed by signal " + str(-status) if status < 0 else ""
    print("gate " + verdict + ", exit " + str(exit_status) + signal_note + ", " + str(round(seconds)) + " s, "
          + str(len(lines)) + " lines logged to " + str(log_path))
    print("command: " + " ".join(command))
    for line in summarize(lines, exit_status, args.tail, args.limit):
        print(line)
    return exit_status


if __name__ == "__main__":
    sys.exit(main())
